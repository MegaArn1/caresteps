"""Visit summary assembly.

Builds the fact table behind M5. Two rules govern this module and both are testable:

1. **Everything asserted must be traceable.** Each item carries ``record_ids`` naming
   the rows it came from, so a reviewer can point at the source of any sentence.
2. **The patient's words stay the patient's words.** Reported symptoms and concerns are
   reproduced, not interpreted, and are explicitly labelled as *reported by the patient*
   so that a reader cannot mistake them for a clinician's finding (M5: "do not rewrite
   as a doctor's diagnosis").

The output is a structured dict, not prose. Prose is generated *from* this structure,
never the other way round, which is what makes "the model cannot add a fact the data
does not contain" enforceable: the narrative step is given this structure and nothing
else.
"""

from __future__ import annotations

import sqlite3
from datetime import date, datetime, timedelta
from typing import Any

from . import repository as repo
from . import stats as stats_mod

# Shown on every summary. Non-negotiable, because a summary printed and carried to a
# clinic is the single most likely artefact in this app to be read as a clinical
# document.
DISCLAIMER = (
    "This page was assembled by a prototype from the user's own records. It is not a "
    "medical report. Numbers are as recorded and may be incomplete. Anything under "
    "'reported by the patient' is what the patient said, not a clinical finding. No "
    "part of this was written or checked by a doctor."
)


def build_summary_facts(
    conn: sqlite3.Connection, user_id: str, days: int = 14, end: date | None = None
) -> dict[str, Any]:
    """Assemble every item that may appear on the summary."""
    profile = repo.get_profile(conn, user_id)
    if not profile:
        raise repo.ValidationError("No profile to summarise")

    end = end or date.today()
    start = end - timedelta(days=days - 1)

    readings = [
        r
        for r in repo.list_readings(conn, user_id, days=days * 3)
        if start.isoformat() <= r["measured_at"][:10] <= end.isoformat()
    ]
    reports = [
        r
        for r in repo.list_medication_reports(conn, user_id, days=days * 3)
        if start.isoformat() <= r["reported_at"][:10] <= end.isoformat()
    ]
    unrecorded = repo.derive_unrecorded(
        conn, user_id, start.isoformat(), end.isoformat()
    )
    barriers = [
        b
        for b in repo.list_barriers(conn, user_id)
        if start.isoformat() <= b["created_at"][:10] <= end.isoformat()
    ]
    actions = [
        a
        for a in repo.list_support_actions(conn, user_id)
        if start.isoformat() <= a["created_at"][:10] <= end.isoformat()
    ]
    questions = repo.list_questions(conn, user_id)
    plan = repo.list_care_plan(conn, user_id)
    meds = repo.list_medications(conn, user_id)

    period_stats = stats_mod.summarize(readings, start, end, label=f"Last {days} days")
    adherence = stats_mod.adherence_summary(reports, unrecorded, start, end)
    coverage = stats_mod.coverage(readings, start, end)

    return {
        "meta": {
            "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
            "period": {"from": start.isoformat(), "to": end.isoformat(), "days": days},
            "patient_label": profile["display_name"],
            "age_band": profile["age_band"],
            "all_simulated": bool(profile["is_simulated"]),
            "disclaimer": DISCLAIMER,
            # Included so a reader can see this was generated by a prototype rather
            # than exported from a clinical system.
            "generator": "CareSteps prototype",
        },
        "coverage": {
            "title": "How complete this record is",
            "window_days": coverage["window_days"],
            "days_with_readings": coverage["days_with_data"],
            "days_without_readings": coverage["missing_days"],
            "missing_dates": coverage["missing_dates"],
            "statement": (
                f"Between {start.isoformat()} and {end.isoformat()} there are readings "
                f"on {coverage['days_with_data']} of {coverage['window_days']} days. "
                f"{coverage['missing_days']} day(s) have no reading recorded."
            ),
            "record_ids": [r["id"] for r in readings],
        },
        "readings": {
            "title": "Blood pressure readings",
            "n": period_stats["n"],
            "sufficient": period_stats["sufficient"],
            "mean_systolic": period_stats["mean_systolic"],
            "mean_diastolic": period_stats["mean_diastolic"],
            "range_systolic": [period_stats["min_systolic"], period_stats["max_systolic"]],
            "range_diastolic": [period_stats["min_diastolic"], period_stats["max_diastolic"]],
            "statement": period_stats["note"],
            "revised_count": period_stats["revised_count"],
            "series": stats_mod.series_for_chart(readings, start, end)["points"],
            "record_ids": [r["id"] for r in readings],
            # No target comparison is emitted. Without a sourced personal target, a
            # "within range" verdict would be an invented clinical judgement (M4).
            "target_comparison": _target_comparison(plan, period_stats),
        },
        "medication": {
            "title": "Medication - what the patient reported",
            "counts": adherence["counts"],
            "labels": adherence["labels"],
            "statement": adherence["interpretation"],
            "caution": adherence["note"],
            "reports": [
                {
                    "status": r["status"],
                    "reported_at": r["reported_at"],
                    "backfilled": bool(r["is_backfilled"]),
                    "note": r["note"],
                    "record_ids": [r["id"]],
                }
                for r in reports
            ],
            "unrecorded_days": [u["scheduled_for"][:10] for u in unrecorded],
            "confirmed_medicines": [
                {
                    "name": m["name"],
                    "confirmed_by_user": bool(m["confirmed_by_user"]),
                    "plan_instruction": m["plan_instruction"],
                }
                for m in meds
            ],
        },
        "reported_by_patient": {
            "title": "Reported by the patient",
            "intro": (
                "These are the patient's own words or notes. They are not diagnoses "
                "and have not been checked by a clinician."
            ),
            "feelings": [
                {
                    "date": r["measured_at"][:10],
                    "text": r["user_feeling"],
                    "record_ids": [r["id"]],
                }
                for r in readings
                if r.get("user_feeling")
            ],
            "notes": [
                {
                    "date": r["measured_at"][:10],
                    "text": r["note"],
                    "record_ids": [r["id"]],
                }
                for r in readings
                if r.get("note")
            ],
            "difficulties": [
                {
                    "date": b["created_at"][:10],
                    "words": b["user_words"],
                    "category": b["category"],
                    "category_confirmed": bool(b["category_confirmed"]),
                    "status": b["status"],
                    "record_ids": [b["id"]],
                    # Rendered differently by the template when false.
                    "label": (
                        "confirmed by the patient"
                        if b["category_confirmed"]
                        else "not confirmed by the patient"
                    ),
                }
                for b in barriers
            ],
        },
        "actions_taken": {
            "title": "What the patient chose to do",
            "items": [
                {
                    "date": a["created_at"][:10],
                    "title": a["title"],
                    "basis_type": a["basis_type"],
                    "basis_label": a["basis_label"],
                    "status": a["status"],
                    "record_ids": [a["id"]],
                }
                for a in actions
            ],
        },
        "questions": {
            "title": "Questions to ask",
            "items": [
                {
                    "text": q["text"],
                    "origin": q["origin"],
                    "include": bool(q["include_in_summary"]),
                    "record_ids": [q["id"]],
                }
                for q in questions
            ],
        },
        "care_plan": {
            "title": "Recorded plan",
            "items": [
                {
                    "instruction": p["instruction"],
                    "source_type": p["source_type"],
                    "source_label": p["source_label"],
                    "confirmed_by_user": bool(p["verified_by_user"]),
                    "is_simulated": bool(p["is_simulated"]),
                    "record_ids": [p["id"]],
                }
                for p in plan
            ],
        },
    }


def _target_comparison(plan: list[dict], period_stats: dict) -> dict | None:
    """Compare against a personal target ONLY if a sourced target exists.

    Returns ``None`` when there is no target with a stated origin. This is the code
    path that makes "no individual goal means no 'on target' judgement" true: there is
    simply nothing for the template to render.
    """
    sourced = [
        p for p in plan if p.get("target_systolic") and p.get("target_source")
    ]
    if not sourced:
        return None
    if not period_stats["sufficient"]:
        return {
            "available": False,
            "reason": "Not enough readings in this period to compare with the recorded target.",
        }
    top = sourced[0]
    return {
        "available": True,
        "target_systolic": top["target_systolic"],
        "target_diastolic": top["target_diastolic"],
        "target_source": top["target_source"],
        # Descriptive only. "Recorded average of 142 against a recorded target of 140"
        # is a statement about two numbers. It is not a statement about control, and
        # the template must not render it as one.
        "statement": (
            f"The recorded average of the top number is {period_stats['mean_systolic']}. "
            f"The target recorded on the plan is {top['target_systolic']} "
            f"(source: {top['target_source']}). This compares two recorded numbers; it "
            "is not an assessment of control."
        ),
    }


# Keys the user is allowed to omit. Used by the edit step, so that "delete this from
# my summary" is a first-class operation rather than an afterthought.
OMITTABLE_KEYS = [
    "reported_by_patient.feelings",
    "reported_by_patient.notes",
    "reported_by_patient.difficulties",
    "actions_taken.items",
    "questions.items",
]


def apply_omissions(facts: dict, omitted: list[str]) -> dict:
    """Return a copy of the facts with user-omitted sections removed.

    The meta block and the readings block are deliberately NOT omittable: a summary
    with the numbers stripped out but the caveats left in would be misleading in the
    other direction. Removing all data is the same as not printing the page.
    """
    import copy

    out = copy.deepcopy(facts)
    for path in omitted or []:
        if path not in OMITTABLE_KEYS:
            continue
        section, _, leaf = path.partition(".")
        if section in out and leaf in out[section]:
            out[section][leaf] = []
            out[section].setdefault("omitted", []).append(path)
    return out


def narrative_context(facts: dict) -> dict:
    """The *only* thing handed to the model when drafting summary prose.

    Trimmed to what a short introduction needs, so the model has no opportunity to
    invent a detail it was not given.
    """
    return {
        "period": facts["meta"]["period"],
        "readings_count": facts["readings"]["n"],
        "readings_sufficient": facts["readings"]["sufficient"],
        "coverage_statement": facts["coverage"]["statement"],
        "medication_statement": facts["medication"]["statement"],
        "recorded_target": facts["readings"].get("target_comparison"),
        "open_difficulties": [
            d["words"]
            for d in facts["reported_by_patient"]["difficulties"]
            if d["status"] == "open"
        ],
        "question_count": len(facts["questions"]["items"]),
        "disclaimer": facts["meta"]["disclaimer"],
    }
